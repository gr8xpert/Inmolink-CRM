import { createHash } from 'node:crypto';
import { ErrorBody, WebsiteFeedParams } from '@inmolink/contracts';
import * as websiteApi from '@inmolink/core/modules/website-api';
import type { RateLimitRule } from '@inmolink/platform/rate-limit';
import type { FastifyZod } from '@inmolink/platform/server';
import type { FastifyRequest } from 'fastify';
import { z } from 'zod';
import { sendStoredFeed } from '../../plugins/site-response';

export const FEED_ROUTE = '/v2/feeds/:token/:file';
/** S9-03: portal feeds (`routes/exports/portal-feeds.ts`), the same token-URL shape and limits. */
export const PORTAL_FEED_ROUTE = '/v2/portal-feeds/:token/:file';

/**
 * Feed consumers poll (hourly at most); the CDN answers the rest, so the origin sees cache misses only. Per IP, and per
 * token (scope `key`: `feedTokenIdentity`) — a token in a public script cannot be used to load the origin.
 */
export const FEED_LIMITS: readonly RateLimitRule[] = [
  { name: 'feed.xml.ip', scope: 'ip', limit: 60, windowSeconds: 60 },
  { name: 'feed.xml.token', scope: 'key', limit: 120, windowSeconds: 3_600 },
];

/**
 * The rate-limit identity of a feed request: a hash of its token (never the token: it would sit in Redis keys), so the
 * S7-04 limiter counts per feed. Undefined for any other route.
 */
export function feedTokenIdentity(req: FastifyRequest): string | undefined {
  const route = req.routeOptions.url;
  if (route !== FEED_ROUTE && route !== PORTAL_FEED_ROUTE) return undefined;
  const token = (req.params as { token?: unknown } | undefined)?.token;
  if (typeof token !== 'string') return undefined;
  const kind = route === FEED_ROUTE ? 'feed' : 'portal-feed';
  return `${kind}:${createHash('sha256').update(token).digest('base64url').slice(0, 22)}`;
}

/** The XML document (OpenAPI only: the body is streamed, never serialized). */
export const FeedXml = z.string().describe('The feed document, `application/xml; charset=utf-8` (gzip when accepted)');

/**
 * Per-site XML feeds (S7-07, PLAN §9.5): `GET /v2/feeds/{token}/kyero.xml` (Kyero v3) and `/inmolink.xml` (generic),
 * the site's inventory as its website API shows it, generated by the worker. The token is the credential (per site,
 * never an API key; redacted from logs and traces): unknown, rotated and revoked tokens answer the same 404. Thin: one
 * core call, then the stored file streamed — gzip as stored for clients that take it (the CDN does), else
 * decompressed on the fly. Public for the CDN when the edge cache is on (`Vary: Accept-Encoding` only: the URL is the
 * key), with the site and feed `Cache-Tag`s (purged on a new run, a rotation or revocation, a site or agency change)
 * and a short `stale-if-error`; never indexed by search engines. With the edge cache off, gzip clients are redirected
 * to a short-lived signed storage URL instead (S8-F1). Exempt from the 150 KB JSON budget (a whole inventory).
 */
export async function websiteFeedRoutes(app: FastifyZod): Promise<void> {
  app.get(
    FEED_ROUTE,
    {
      schema: {
        tags: ['website-v2'],
        operationId: 'websiteV2.getFeed',
        summary:
          "The site's XML feed: `kyero.xml` (Kyero v3) or `inmolink.xml` (generic). The token URL is the credential",
        params: WebsiteFeedParams,
        response: {
          200: FeedXml,
          302: z.null().describe('Edge cache off: a short-lived signed storage URL serving the gzip feed (`Location`)'),
          304: z.null().describe('Not modified (`If-None-Match`)'),
          404: ErrorBody.describe('SITE_FEED_NOT_FOUND: unknown, rotated or revoked token, or no feed yet'),
        },
      },
      config: { rateLimit: FEED_LIMITS },
    },
    async (req, reply) => sendStoredFeed(req, reply, await websiteApi.siteFeedFile(req.params.token, req.params.file)),
  );
}
