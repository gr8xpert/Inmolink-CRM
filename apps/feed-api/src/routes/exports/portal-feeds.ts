import { createGunzip } from 'node:zlib';
import { ErrorBody, PortalFeedParams } from '@inmolink/contracts';
import * as exportsModule from '@inmolink/core/modules/exports';
import { cacheControl, weakCompareEtag } from '@inmolink/platform/http';
import type { RateLimitRule } from '@inmolink/platform/rate-limit';
import type { FastifyZod } from '@inmolink/platform/server';
import { z } from 'zod';
import { edgePublic, publicCacheControl, ruleOf } from '../../plugins/edge-cache';
import { acceptsGzip, FeedXml, PORTAL_FEED_ROUTE } from '../website-api/feeds';

/** Default portal feed requests per minute per IP (`PORTAL_FEED_IP_PER_MINUTE`). */
export const PORTAL_FEED_IP_DEFAULT = 3_000;

/**
 * Portals poll many agencies' feeds from a few addresses (Kyero, thinkSPAIN, A Place in the Sun crawlers), and a
 * nightly regeneration purges every feed so a portal re-fetches them all from the origin: the per-IP ceiling is
 * configurable and high (S9-03 review). Per token (scope `key`: `feedTokenIdentity`) it stays tight — a portal polls a
 * feed hourly at most, and a leaked token cannot be used to load the origin.
 */
export function portalFeedLimits(ipPerMinute = PORTAL_FEED_IP_DEFAULT): readonly RateLimitRule[] {
  return [
    { name: 'portal-feed.xml.ip', scope: 'ip', limit: ipPerMinute, windowSeconds: 60 },
    { name: 'portal-feed.xml.token', scope: 'key', limit: 60, windowSeconds: 3_600 },
  ];
}

/**
 * Portal feeds (S9-03, PLAN §7 M7): `GET /v2/portal-feeds/{token}/kyero.xml` (Kyero v3: Kyero, thinkSPAIN, A Place in
 * the Sun) or `/inmolink.xml` (generic XML) — one portal connection's feed, generated by the worker into object
 * storage. The token is the credential (per connection, never an API key; redacted from logs and traces): unknown,
 * rotated and revoked tokens, connections turned off, agencies not verified and feeds not generated yet all answer
 * the same 404. Thin, like the site feeds: one core call (one statement: a SECURITY DEFINER lookup that reads no
 * credential), then the stored file streamed — gzip as stored when the client takes it, else decompressed on the
 * fly — or, with the edge cache off, a redirect to a short-lived signed storage URL. CDN-cacheable with the edge cache
 * on (`Vary: Accept-Encoding`, the connection's `Cache-Tag`, purged on a new file, a token change or the connection
 * turned off) and a short `stale-if-error`; never indexed. Exempt from the 150 KB JSON budget (a whole inventory).
 */
export async function portalFeedRoutes(app: FastifyZod, opts: { ipPerMinute?: number } = {}): Promise<void> {
  app.get(
    PORTAL_FEED_ROUTE,
    {
      schema: {
        tags: ['website-v2'],
        operationId: 'websiteV2.getPortalFeed',
        summary:
          "A portal connection's XML feed: `kyero.xml` (Kyero v3) or `inmolink.xml` (generic). The token URL is the credential",
        params: PortalFeedParams,
        response: {
          200: FeedXml,
          302: z.null().describe('Edge cache off: a short-lived signed storage URL serving the gzip feed (`Location`)'),
          304: z.null().describe('Not modified (`If-None-Match`)'),
          404: ErrorBody.describe(
            'PORTAL_FEED_NOT_FOUND: unknown, rotated or revoked token, connection off, or no feed yet',
          ),
        },
      },
      config: { rateLimit: portalFeedLimits(opts.ipPerMinute) },
    },
    async (req, reply) => {
      const file = await exportsModule.portalFeedFile(req.params.token, req.params.file);
      const gzip = acceptsGzip(req);
      // One ETag per stored file and encoding (the bytes differ).
      const etag = gzip ? file.etag : `${file.etag.slice(0, -1)}.identity"`;
      const rule = ruleOf(req);
      const shared = edgePublic(req, rule) && file.tags !== null;
      reply
        .header('Cache-Control', shared ? publicCacheControl(rule) : cacheControl.private(0))
        .header('ETag', etag)
        .header('Vary', 'Accept-Encoding')
        .header('X-Robots-Tag', 'noindex, nofollow')
        .header('Referrer-Policy', 'no-referrer')
        .header('X-Content-Type-Options', 'nosniff');
      if (shared && file.tags) reply.header('Cache-Tag', file.tags.join(','));
      if (weakCompareEtag(req.headers['if-none-match'], etag)) return reply.code(304).send(null);
      if (!shared && gzip) {
        return reply.header('Cache-Control', cacheControl.noStore()).redirect(await file.signedUrl(), 302);
      }
      const body = await file.open();
      reply.type('application/xml; charset=utf-8');
      if (gzip) return reply.header('Content-Encoding', 'gzip').send(body as unknown as string);
      return reply.send(body.pipe(createGunzip()) as unknown as string);
    },
  );
}
