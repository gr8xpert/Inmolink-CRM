import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { LocaleConfig } from './locales';
import type { Catalog, Catalogs, MessageTree } from './server';

/**
 * Catalog tooling behind `pnpm i18n:check` and `pnpm i18n:draft` (PATTERNS §21), Node only. The
 * default UI locale (EN) is the source of truth. Hand-written locales (EN, ES) must match it key for
 * key; other locales are drafted, and `messages/<locale>/_drafts.json` records which of their keys
 * still need a translation (`todo`: EN text copied as a placeholder) or a human review (`draft`: AI
 * text). `src/catalogs.generated.ts` bundles the catalogs of the configured locales.
 */
export type DraftState = 'todo' | 'draft';
export type DraftIndex = Record<string, Record<string, DraftState>>;

export const MESSAGES_DIR = fileURLToPath(new URL('../messages/', import.meta.url));
export const CATALOG_INDEX = fileURLToPath(new URL('../src/catalogs.generated.ts', import.meta.url));
const DRAFTS_FILE = '_drafts.json';

/** Path-safe locale codes only: the code becomes a directory name. */
const SAFE_LOCALE = /^[a-z]{2,3}(-[A-Z]{2})?$/;

/** Namespace file names of one locale (`auth`, …); `_`-prefixed files are bookkeeping. */
function namespaceFiles(dir: string, locale: string): string[] {
  if (!SAFE_LOCALE.test(locale)) throw new Error(`i18n: invalid locale code ${JSON.stringify(locale)}`);
  const localeDir = join(dir, locale);
  if (!existsSync(localeDir)) return [];
  return readdirSync(localeDir)
    .filter((f) => f.endsWith('.json') && !f.startsWith('_'))
    .map((f) => {
      const ns = f.slice(0, -'.json'.length);
      // The name becomes an import path and an object key in catalogs.generated.ts.
      if (!/^[a-z][a-z0-9-]*$/.test(ns)) throw new Error(`i18n: invalid namespace file name ${JSON.stringify(f)}`);
      return ns;
    })
    .sort();
}

/** One locale's own catalog (no fallback) from disk. Missing locale directory → `{}`. */
export function readCatalog(locale: string, dir: string = MESSAGES_DIR): Catalog {
  const catalog: Catalog = {};
  for (const ns of namespaceFiles(dir, locale)) {
    catalog[ns] = JSON.parse(readFileSync(join(dir, locale, `${ns}.json`), 'utf8')) as MessageTree;
  }
  return catalog;
}

/** The configured UI locales' catalogs from disk. */
export function readCatalogs(config: LocaleConfig, dir: string = MESSAGES_DIR): Catalogs {
  return Object.fromEntries(config.ui.locales.map((l) => [l, readCatalog(l, dir)]));
}

/** Source of `catalogs.generated.ts` for the configured locales and the catalog files on disk. */
export function renderCatalogIndex(config: LocaleConfig, dir: string = MESSAGES_DIR): string {
  const imports: string[] = [];
  const entries: string[] = [];
  for (const locale of [...config.ui.locales].sort()) {
    const names = namespaceFiles(dir, locale).map((ns) => {
      const name = `m${imports.length}`;
      imports.push(`import ${name} from '../messages/${locale}/${ns}.json' with { type: 'json' };`);
      return `${JSON.stringify(ns)}: ${name}`;
    });
    entries.push(`  ${JSON.stringify(locale)}: { ${names.join(', ')} },`);
  }
  return [
    '// Generated by `pnpm i18n:draft` from locales.json and messages/ — do not edit.',
    ...imports,
    '',
    'export const CATALOGS = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

const readIndex = (file: string) => (existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : '');

/** Writes `catalogs.generated.ts`; returns whether it changed. */
export function writeCatalogIndex(config: LocaleConfig, dir: string = MESSAGES_DIR, file = CATALOG_INDEX): boolean {
  const next = renderCatalogIndex(config, dir);
  if (readIndex(file) === next) return false;
  writeFileSync(file, next);
  return true;
}

/** `{ signup: { title: 'x' } }` → `{ 'signup.title': 'x' }`. Non-string leaves are reported by `check`. */
export function flatten(tree: MessageTree, prefix = ''): Map<string, unknown> {
  const out = new Map<string, unknown>();
  for (const [k, v] of Object.entries(tree)) {
    if (v !== null && typeof v === 'object' && !Array.isArray(v)) {
      for (const [kk, vv] of flatten(v as MessageTree, `${prefix}${k}.`)) out.set(kk, vv);
    } else {
      out.set(`${prefix}${k}`, v);
    }
  }
  return out;
}

/** Top-level ICU argument names: `Hi {name}, {count, plural, one {# day} other {# days}}` → name, count. */
export function placeholders(message: string): string[] {
  const names = new Set<string>();
  let depth = 0;
  for (let i = 0; i < message.length; i++) {
    const c = message[i];
    if (c === '{') {
      if (depth === 0) {
        const m = /^\{\s*([A-Za-z_][\w]*)\s*[,}]/.exec(message.slice(i));
        if (m?.[1]) names.add(m[1]);
      }
      depth++;
    } else if (c === '}' && depth > 0) {
      depth--;
    }
  }
  return [...names].sort();
}

function readDrafts(dir: string, locale: string): DraftIndex {
  try {
    return JSON.parse(readFileSync(join(dir, locale, DRAFTS_FILE), 'utf8')) as DraftIndex;
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') return {};
    throw err;
  }
}

export interface CheckResult {
  errors: string[];
  warnings: string[];
  /** Per drafted locale: keys still `todo` / in `draft`. */
  drafts: Record<string, Record<DraftState, number>>;
}

/** Validates every configured UI locale's catalog against the default locale. Pure read. */
export function checkCatalogs(
  config: LocaleConfig,
  dir: string = MESSAGES_DIR,
  indexFile: string | null = dir === MESSAGES_DIR ? CATALOG_INDEX : null,
): CheckResult {
  const errors: string[] = [];
  if (indexFile && readIndex(indexFile) !== renderCatalogIndex(config, dir)) {
    errors.push('catalogs.generated.ts is out of date — run `pnpm i18n:draft`');
  }
  const warnings: string[] = [];
  const drafts: CheckResult['drafts'] = {};
  const source = config.ui.default;
  const reference = readCatalog(source, dir);
  if (Object.keys(reference).length === 0) errors.push(`${source}: no catalogs in ${join(dir, source)}`);

  for (const locale of config.ui.locales) {
    const handwritten = config.ui.handwritten.includes(locale);
    const catalog = locale === source ? reference : readCatalog(locale, dir);
    const index = readDrafts(dir, locale);
    if (handwritten && Object.keys(index).some((ns) => Object.keys(index[ns] ?? {}).length > 0)) {
      errors.push(`${locale}: is hand-written but has ${DRAFTS_FILE} entries — translate them and remove the file`);
    }
    if (!handwritten) drafts[locale] = { todo: 0, draft: 0 };
    const namespaces = new Set([...Object.keys(reference), ...Object.keys(catalog)]);
    for (const ns of namespaces) {
      const ref = reference[ns] ? flatten(reference[ns]) : new Map<string, unknown>();
      const own = catalog[ns] ? flatten(catalog[ns]) : new Map<string, unknown>();
      const fix = handwritten ? 'write it by hand' : 'run `pnpm i18n:draft`';
      if (!reference[ns]) {
        errors.push(`${locale}: namespace "${ns}" does not exist in ${source}`);
        continue;
      }
      for (const [key, value] of own) {
        if (typeof value !== 'string' || value.trim() === '')
          errors.push(`${locale}: ${ns}.${key} is empty or not text`);
      }
      for (const [key, refValue] of ref) {
        if (typeof refValue !== 'string') continue;
        const value = own.get(key);
        if (value === undefined) {
          errors.push(`${locale}: ${ns}.${key} is missing (${fix})`);
          continue;
        }
        if (typeof value !== 'string') continue;
        const want = placeholders(refValue).join(',');
        const got = placeholders(value).join(',');
        if (want !== got) errors.push(`${locale}: ${ns}.${key} uses {${got}} but ${source} uses {${want}}`);
      }
      for (const key of own.keys()) {
        if (!ref.has(key)) errors.push(`${locale}: ${ns}.${key} does not exist in ${source} — remove it`);
      }
      if (!handwritten) {
        for (const [key, state] of Object.entries(index[ns] ?? {})) {
          if (!ref.has(key)) errors.push(`${locale}: ${DRAFTS_FILE} lists ${ns}.${key}, which does not exist`);
          else (drafts[locale] as Record<DraftState, number>)[state]++;
        }
      }
    }
  }

  let dirs: string[] = [];
  try {
    dirs = readdirSync(dir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name);
  } catch {}
  for (const d of dirs) {
    if (!config.ui.locales.includes(d)) warnings.push(`${d}: catalog directory for a locale not in locales.json`);
  }
  return { errors, warnings, drafts };
}

function unflatten(entries: [string, string][]): MessageTree {
  const root: MessageTree = {};
  for (const [key, value] of entries) {
    const parts = key.split('.');
    let node = root;
    for (const part of parts.slice(0, -1)) {
      node[part] ??= {};
      node = node[part] as MessageTree;
    }
    node[parts.at(-1) as string] = value;
  }
  return root;
}

/** Machine translation hook — wired to the AI gateway in S12-01. Returns one text per input. */
export type DraftTranslate = (texts: string[], from: string, to: string) => Promise<string[]>;

export interface DraftResult {
  /** Per drafted locale: keys added and keys removed. */
  locales: Record<string, { added: number; removed: number }>;
  /** Keys a hand-written locale is missing; `draft` never fills those. */
  handwrittenMissing: string[];
  /** Whether `catalogs.generated.ts` was rewritten. */
  indexChanged?: boolean;
}

/**
 * Brings every drafted locale in line with the default locale: missing keys are added (machine
 * translated when `translate` is given and marked `draft`, else the source text marked `todo`), keys
 * gone from the source are removed. Existing translations are kept. Hand-written locales are never
 * written. Idempotent.
 */
export async function draftCatalogs(
  config: LocaleConfig,
  options: { dir?: string; indexFile?: string | null; translate?: DraftTranslate } = {},
): Promise<DraftResult> {
  const dir = options.dir ?? MESSAGES_DIR;
  const indexFile = options.indexFile === undefined ? (dir === MESSAGES_DIR ? CATALOG_INDEX : null) : options.indexFile;
  const source = config.ui.default;
  const reference: Catalog = readCatalog(source, dir);
  const result: DraftResult = { locales: {}, handwrittenMissing: [] };

  for (const locale of config.ui.locales) {
    if (locale === source) continue;
    const catalog = readCatalog(locale, dir);
    if (config.ui.handwritten.includes(locale)) {
      for (const [ns, tree] of Object.entries(reference)) {
        const own = catalog[ns] ? flatten(catalog[ns]) : new Map();
        for (const key of flatten(tree).keys())
          if (!own.has(key)) result.handwrittenMissing.push(`${locale}: ${ns}.${key}`);
      }
      continue;
    }
    const index = readDrafts(dir, locale);
    const nextIndex: DraftIndex = {};
    const stats = { added: 0, removed: 0 };
    mkdirSync(join(dir, locale), { recursive: true });
    for (const [ns, tree] of Object.entries(reference)) {
      const ref = flatten(tree);
      const own = catalog[ns] ? flatten(catalog[ns]) : new Map<string, unknown>();
      const missing = [...ref.entries()].filter(([k, v]) => typeof v === 'string' && typeof own.get(k) !== 'string');
      const texts = missing.map(([, v]) => v as string);
      const translated = options.translate && texts.length > 0 ? await options.translate(texts, source, locale) : null;
      const filled = new Map<string, string>(missing.map(([k], i) => [k, translated?.[i] ?? texts[i] ?? '']));
      const state: DraftState = translated ? 'draft' : 'todo';
      const entries: [string, string][] = [];
      const nsIndex: Record<string, DraftState> = {};
      for (const [key, refValue] of ref) {
        if (typeof refValue !== 'string') continue;
        const existing = own.get(key);
        if (typeof existing === 'string') {
          entries.push([key, existing]);
          const prior = index[ns]?.[key];
          if (prior) nsIndex[key] = prior;
        } else {
          entries.push([key, filled.get(key) ?? refValue]);
          nsIndex[key] = state;
          stats.added++;
        }
      }
      stats.removed += [...own.keys()].filter((k) => !ref.has(k)).length;
      writeFileSync(join(dir, locale, `${ns}.json`), `${JSON.stringify(unflatten(entries), null, 2)}\n`);
      if (Object.keys(nsIndex).length > 0) nextIndex[ns] = nsIndex;
    }
    writeFileSync(join(dir, locale, DRAFTS_FILE), `${JSON.stringify(nextIndex, null, 2)}\n`);
    result.locales[locale] = stats;
  }
  if (indexFile) result.indexChanged = writeCatalogIndex(config, dir, indexFile);
  return result;
}
