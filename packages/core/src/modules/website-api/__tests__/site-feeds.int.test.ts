async function refusal(promise: Promise<unknown>): Promise<string> {
  try {
    await promise;
  } catch (err) {
    if (isAppError(err)) return err.code;
    throw err;
  }
  return 'served';
}

/** A served file as a consumer gets it: the stored gzip, decompressed. */
async function fetchFeed(token: string, file: websiteApi.SiteFeedFileName): Promise<string> {
  const served = await websiteApi.siteFeedFile(token, file);
  return gunzipSync(Buffer.concat(await (await served.open()).toArray())).toString('utf8');
}

const runFeed = (siteId: string) => websiteApi.generateSiteFeed(siteId, { log });

/** Runs an event's feed subscribers as the dispatcher would. */
async function publish(type: string, payload: unknown, agencyId: string): Promise<void> {
  for (const sub of defaultSubscribers.get(type, 1)) {
    if (!sub.name.startsWith('websiteApi.feed.')) continue;
    await sub.handler(payload as never, {
      eventId: newId(),
      agencyId,
      type,
      version: 1,
      createdAt: new Date(),
      attempt: 1,
    });
  }
}

