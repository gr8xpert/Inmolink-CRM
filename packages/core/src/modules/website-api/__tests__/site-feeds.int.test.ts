const tokens: Record<string, string> = {};

describe('per-site XML feeds (S7-07)', () => {
  it('[S7-07] the generated XML feed validates against the Kyero schema fixture (and the generic one)', async () => {
    for (const site of [S.network, S.own]) {
      tokens[site] = (await as(a, (ctx) => websites.rotateSiteFeed(ctx, { siteId: site }))).secret.token;
    }
    // No run yet: nothing is served.
    expect(await refusal(websiteApi.siteFeedFile(tokens[S.network] as string, 'kyero.xml'))).toBe(
      'SITE_FEED_NOT_FOUND',
    );
    const result = await runFeed(S.network);
    expect(result).toMatchObject({ items: 3, kyero: 3 });
    const kyero = await fetchFeed(tokens[S.network] as string, 'kyero.xml');
    const generic = await fetchFeed(tokens[S.network] as string, 'inmolink.xml');
    expect(await schemaErrors(kyero, KYERO_XSD)).toEqual([]);
    expect(await schemaErrors(generic, GENERIC_XSD)).toEqual([]);
    expect(kyero).toContain('<es>Villa soleada con piscina.</es>');
    expect(kyero).toContain('<price_freq>month</price_freq>');
    const feed = await as(a, (ctx) => websites.getSiteFeed(ctx, { siteId: S.network }));
    expect(feed).toMatchObject({ enabled: true, itemCount: 3, kyeroCount: 3, lastError: null });
    expect(feed.tokenHint).toBe((tokens[S.network] as string).slice(-4));
  });

  it('[S7-07] the feed has the same inventory policy, white-label and overrides as /v2/listings', async () => {
    const network = await websiteApi.siteForKey({ agencyId: a.agencyId, siteId: S.network }, newId());
    const sitemap = await websiteApi.sitemap(network, WebsiteSitemapQuery.parse({ lang: 'en', limit: 100 }));
    const generic = await fetchFeed(tokens[S.network] as string, 'inmolink.xml');
    const feedRefs = [...generic.matchAll(/<item kind="[A-Z]+" ref="([^"]+)"/g)].map((m) => m[1]).sort();
    expect(feedRefs).toEqual(sitemap.items.map((i) => i.ref).sort());
    // The network listing: the site's reference, the site agency's override, never the owner's identity.
    const bRef = (await as(b, (ctx) => properties.getListing(ctx, L.bVilla))).ref as string;
    const bDetail = await websiteApi.listingDetail(network, feedRefs.find((r) => r?.startsWith('CF-')) as string, 'en');
    expect(bDetail.title).toBe(`Override title ${RUN}`);
    expect(generic).toContain(`<title>Override title ${RUN}</title>`);
    for (const doc of [generic, await fetchFeed(tokens[S.network] as string, 'kyero.xml')]) {
      expect(doc).not.toContain(OWNER_MAIL);
      expect(doc).not.toContain('ownerhaus');
      expect(doc).not.toContain('Ownerhaus');
      expect(doc).not.toContain(bRef);
      expect(doc).not.toContain(b.agencyId);
      expect(doc.toLowerCase()).not.toContain('commission');
      // The presenting agency is the site's.
    }
    expect(generic).toMatch(/<agency><name>[^<]+<\/name>/);
    // An OWN_ONLY site shows only the agency's listings.
    await runFeed(S.own);
    const own = await fetchFeed(tokens[S.own] as string, 'inmolink.xml');
    expect(own.match(/<item /g)).toHaveLength(2);
    expect(own).not.toContain('CF-');
  });

  it('[S7-07] the token URL is per site and unguessable; rotation stops the old token, revocation the feed', async () => {
    const site = S.network;
    const old = tokens[site] as string;
    expect(old).toMatch(/^[A-Za-z0-9_-]{43}$/);
    expect(old).not.toBe(tokens[S.own]);
    // Only the keyed hash is stored, never the token.
    const stored = await system((tx) =>
      tx.execute<{ token_hash: string }>(sql`select token_hash from website_feeds where site_id = ${site}`),
    );
    expect(stored.rows[0]?.token_hash).not.toContain(old);
    // An API key of the site is no feed token.
    const key = await as(a, (ctx) =>
      identity.createApiKey(ctx, {
        name: 'WP',
        kind: 'SECRET',
        scopes: ['listings:read'],
        allowedOrigins: [],
        siteId: site,
      }),
    );
    expect(await websites.feedByToken(key.secret)).toBeNull();
    // A token of the right shape that was never issued.
    expect(
      await refusal(websiteApi.siteFeedFile(`${old.slice(0, -1)}${old.endsWith('A') ? 'B' : 'A'}`, 'kyero.xml')),
    ).toBe('SITE_FEED_NOT_FOUND');

    const rotated = (await as(a, (ctx) => websites.rotateSiteFeed(ctx, { siteId: site }))).secret;
    expect(rotated.paths.kyero).toBe(`/v2/feeds/${rotated.token}/kyero.xml`);
    expect(await refusal(websiteApi.siteFeedFile(old, 'kyero.xml'))).toBe('SITE_FEED_NOT_FOUND');
    expect(await refusal(websiteApi.siteFeedFile(rotated.token, 'kyero.xml'))).toBe('served');
    // The other site's feed is untouched.
    expect(await refusal(websiteApi.siteFeedFile(tokens[S.own] as string, 'kyero.xml'))).toBe('served');
    // The CDN copies of the old URL are purged (`f`) and the feed is regenerated within seconds.
    await publish('websites.feed.changed', { siteId: site, agencyId: a.agencyId, action: 'ROTATED' }, a.agencyId);
    expect(purgeEnqueues).toEqual([a.agencyId]);
    expect(feedEnqueues).toEqual([
      { siteId: site, throttleMs: websiteApi.SITE_FEED_SOON_MS, debounceKey: `site-feed:${site}` },
    ]);
    tokens[site] = rotated.token;

    // Members may look, never manage.
    const ownFiles = () => [...store.objects.keys()].filter((k) => k.startsWith(`feeds/site-feeds/${S.own}/`));
    expect(ownFiles()).toHaveLength(2);
    feedEnqueues.length = 0;
    await as(a, (ctx) => websites.revokeSiteFeed(ctx, { siteId: S.own }));
    expect(await refusal(websiteApi.siteFeedFile(tokens[S.own] as string, 'kyero.xml'))).toBe('SITE_FEED_NOT_FOUND');
    expect((await as(a, (ctx) => websites.getSiteFeed(ctx, { siteId: S.own }))).enabled).toBe(false);
    // The run is forgotten and its stored files are deleted by the worker.
    const run = await system((tx) =>
      tx.execute<{ run_id: string | null }>(sql`select run_id from website_feeds where site_id = ${S.own}`),
    );
    expect(run.rows[0]?.run_id).toBeNull();
    const deletes: unknown[] = [];
    const spy = vi
      .spyOn(websiteApi.websiteApiJobs.deleteSiteFeedFiles, 'enqueue')
      .mockImplementation(async (payload) => {
        deletes.push(payload);
        return { id: newId() };
      });
    await publish('websites.feed.changed', { siteId: S.own, agencyId: a.agencyId, action: 'REVOKED' }, a.agencyId);
    spy.mockRestore();
    expect(deletes).toHaveLength(1);
    await websiteApi.websiteApiJobs.deleteSiteFeedFiles.spec.run(deletes[0] as never, jobCtx('delete'));
    expect(ownFiles()).toEqual([]);
    expect(await refusal(as(b, (ctx) => websites.rotateSiteFeed(ctx, { siteId: site })))).toBe('SITE_NOT_FOUND');
  });

  it('[S7-07] a run is idempotent: the newest run is served, older files are deleted, a late run never wins', async () => {
    const site = S.network;
    const before = await websiteApi.siteFeedFile(tokens[site] as string, 'kyero.xml');
    const second = await runFeed(site);
    const after = await websiteApi.siteFeedFile(tokens[site] as string, 'kyero.xml');
    // Same inventory → same content → same strong ETag; one run's files stored for the site.
    expect(after.etag).toBe(before.etag);
    const keys = [...store.objects.keys()].filter((k) => k.startsWith(`feeds/site-feeds/${site}/`));
    expect(keys.sort()).toEqual(
      [
        `feeds/site-feeds/${site}/${second.runId}/inmolink.xml.gz`,
        `feeds/site-feeds/${site}/${second.runId}/kyero.xml.gz`,
      ].sort(),
    );
    // A run that started before the recorded one is not recorded.
    const late = await system((tx) =>
      websites.recordFeedRun(tx, {
        siteId: site,
        runId: newId(),
        startedAt: new Date(Date.now() - 3_600_000),
        generatedAt: new Date(),
        itemCount: 0,
        kyeroCount: 0,
        kyeroSha256: 'x',
        genericSha256: 'x',
      }),
    );
    expect(late).toEqual({ recorded: false, previousRunId: null });
    // The job purges the feed's edge copies after a recorded run.
    await websiteApi.websiteApiJobs.generateSiteFeed.spec.run({ siteId: site, agencyId: a.agencyId }, jobCtx('feed'));
    expect(purgeEnqueues).toEqual([a.agencyId]);
  });

  it("[S7-07] listing and site changes queue the agency's live feeds, throttled per site", async () => {
    await publish('search.publicDocs.changed', { targetIds: [L.aVilla], developmentIds: [] }, a.agencyId);
    // Only the live feed (the OWN_ONLY site's was revoked), behind the throttle window.
    expect(feedEnqueues).toEqual([
      {
        siteId: S.network,
        throttleMs: websiteApi.SITE_FEED_THROTTLE_MS,
        debounceKey: `site-feed:${S.network}`,
      },
    ]);
    feedEnqueues.length = 0;
    await publish('websites.site.changed', { siteId: S.own, agencyId: a.agencyId, version: 2 }, a.agencyId);
    expect(feedEnqueues).toEqual([]);
    await publish('websites.site.changed', { siteId: S.network, agencyId: a.agencyId, version: 2 }, a.agencyId);
    expect(feedEnqueues.map((e) => e.siteId)).toEqual([S.network]);
    // Another agency's changes queue nothing of a's.
    feedEnqueues.length = 0;
    await publish('search.publicDocs.changed', { targetIds: [L.bVilla], developmentIds: [] }, b.agencyId);
    expect(feedEnqueues).toEqual([]);
  });

  it('[S7-07] a retried rotation with the same Idempotency-Key answers the same token and rotates nothing', async () => {
    const site = S.network;
    const key = `rotate-${newId()}`;
    const first = await as(a, (ctx) => websites.rotateSiteFeed(ctx, { siteId: site }, { idempotencyKey: key }));
    const retry = await as(a, (ctx) => websites.rotateSiteFeed(ctx, { siteId: site }, { idempotencyKey: key }));
    expect(first.replayed).toBe(false);
    expect(retry).toMatchObject({ replayed: true, secret: { token: first.secret.token } });
    expect(await refusal(websiteApi.siteFeedFile(first.secret.token, 'kyero.xml'))).toBe('served');
    // Another rotation, then the old key again: a new token, never the old one back.
    const other = await as(a, (ctx) => websites.rotateSiteFeed(ctx, { siteId: site }));
    const reused = await as(a, (ctx) => websites.rotateSiteFeed(ctx, { siteId: site }, { idempotencyKey: key }));
    expect(reused.replayed).toBe(false);
    expect(new Set([first.secret.token, other.secret.token, reused.secret.token]).size).toBe(3);
    expect(await refusal(websiteApi.siteFeedFile(first.secret.token, 'kyero.xml'))).toBe('SITE_FEED_NOT_FOUND');
    tokens[site] = reused.secret.token;
  });

  it('[S7-07] a document that fails the website contract is left out and counted, not the whole feed', async () => {
    const saved = await system((tx) =>
      tx.execute<{ locale: string; detail: unknown }>(
        sql`select locale, detail from listing_read_models where target_id = ${L.aRent}`,
      ),
    );
    await system((tx) =>
      tx.execute(sql`update listing_read_models set detail = jsonb_set(detail, '{bedrooms}', '"many"')
                      where target_id = ${L.aRent}`),
    );
    try {
      const result = await runFeed(S.network);
      expect(result).toMatchObject({ items: 2, invalid: 2 });
      const generic = await fetchFeed(tokens[S.network] as string, 'inmolink.xml');
      expect(generic.match(/<item /g)).toHaveLength(2);
    } finally {
      for (const r of saved.rows) {
        await system((tx) =>
          tx.execute(sql`update listing_read_models set detail = ${JSON.stringify(r.detail)}::jsonb
                          where target_id = ${L.aRent} and locale = ${r.locale}`),
        );
      }
    }
    expect(await runFeed(S.network)).toMatchObject({ items: 3, invalid: 0 });
  });

  it('[S7-07] a feed of an agency that is not verified is not served', async () => {
    const site = S.network;
    await setAgencyStatus(a.agencyId, 'SUSPENDED');
    await cache.delete(websites.siteCacheKey(site));
    try {
      expect(await refusal(websiteApi.siteFeedFile(tokens[site] as string, 'kyero.xml'))).toBe('SITE_FEED_NOT_FOUND');
      expect(await runFeed(site)).toEqual({ skipped: 'not-verified' });
    } finally {
      await setAgencyStatus(a.agencyId, 'VERIFIED');
      await cache.delete(websites.siteCacheKey(site));
    }
  });
});
