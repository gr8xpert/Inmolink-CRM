const as = <T>(m: Founder, fn: (ctx: Ctx) => Promise<T>) =>
  withMemberCtx({ userId: m.userId, agencyId: m.agencyId, requestId: newId(), locale: 'en' }, fn);
const system = <T>(fn: Parameters<typeof withSystem<T>>[1]) => withSystem('site-feeds.test', fn);

async function update(m: Founder, id: string, patch: Partial<UpdateListingBody>): Promise<void> {
  await as(m, async (ctx) =>
    properties.updateListing(
      ctx,
      id,
      UpdateListingBody.parse({ ...patch, version: (await properties.getListing(ctx, id)).version }),
    ),
  );
  await system((tx) => search.rebuildReadModels(tx, 'LISTING', [id]));
}

async function listing(m: Founder, body: Partial<CreateListingBody>, texts: Record<string, string>): Promise<string> {
  const { id } = await as(m, (ctx) =>
    properties.createListing(
      ctx,
      CreateListingBody.parse({
        propertyTypeId: ids.villa,
        locationId: ids.city,
        priceCents: 30_000_000,
        energyRating: 'B',
        ...body,
      }),
    ),
  );
  for (const [locale, description] of Object.entries(texts)) {
    await as(m, async (ctx) =>
      properties.saveListingTranslation(ctx, id, locale, {
        version: (await properties.getListing(ctx, id)).version,
        title: `Villa ${locale} ${RUN}`,
        description,
      }),
    );
  }
  await update(m, id, { status: 'ACTIVE', visibility: 'PUBLIC', shareScope: 'ALL' });
  return id;
}

