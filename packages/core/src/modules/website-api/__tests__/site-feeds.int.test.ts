/**
 * Per-site XML feeds (S7-07): generated by the worker job from the website API's own read path — the same inventory
 * policy, white-label and overrides as `/v2/listings` — validated against the Kyero schema fixture, served by an
 * unguessable per-site token that rotation and revocation turn off, regenerated (throttled) when listings or the site
 * change. Object storage is the platform's memory store.
 */

const RUN = newId().slice(-8);
const log = createLogger({ service: 'site-feed-test', level: 'silent' });
const jobCtx = (id: string) => ({
  log,
  jobId: id,
  attempt: 1,
  progress: async () => {},
  signal: new AbortController().signal,
});

