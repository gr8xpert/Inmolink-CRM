/**
 * Per-site XML feeds (S7-07, PLAN §9.5): the token side. An agency admin turns a site's feed on (or rotates its
 * token) and gets the feed URLs once: `/v2/feeds/<token>/kyero.xml` and `/inmolink.xml` on the website API host. The
 * token is 32 random bytes, per site, never the API key, and stored only as its keyed hash; feed-api finds a feed by
 * that hash and compares it again in constant time. Rotating replaces the hash at once (the old URL answers 404 and
 * its CDN copies are purged, `websites.feed.changed`); revoking turns the feed off. The files themselves are written by
 * the website-api generator (worker) and recorded here (`recordFeedRun`).
 */
import type { SiteFeedDto, SiteFeedSecretDto, SiteParams } from '@inmolink/contracts';
import { type Tx, withPublicRead } from '@inmolink/db';
import { clock } from '@inmolink/platform/clock';
import { hmacSha256, hmacSha256Candidates, newToken, safeEqual } from '@inmolink/platform/crypto';
import { AppError } from '@inmolink/platform/errors';
import { emit } from '@inmolink/platform/outbox';
import type { Ctx } from '../../context';
import * as compliance from '../compliance';
import { websitesEvents } from './events';
import * as feedsRepo from './feeds-repo';
import { assertCan } from './policy';
import * as repo from './repo';

const TOKEN_PURPOSE = 'websites.feed-token';
let tokenKey: Buffer | undefined;

/** Boot (api and feed-api): the key feed tokens are hashed with (`HMAC_KEY`, purpose-separated). */
export function configureSiteFeeds(options: { tokenKey: string }): void {
  if (!options.tokenKey) throw new Error('websites: feed tokenKey is required');
  tokenKey = Buffer.from(options.tokenKey);
}

function tokenHashOf(value: string, purpose: string): string {
  if (!tokenKey) throw new Error('websites: configureSiteFeeds() was not called');
  return hmacSha256(tokenKey, purpose, value);
}

const tokenHash = (token: string) => tokenHashOf(token, TOKEN_PURPOSE);

/** Where a feed file is served, relative to the website API host. */
export const siteFeedPath = (token: string, file: 'kyero.xml' | 'inmolink.xml') => `/v2/feeds/${token}/${file}`;

function toFeedDto(siteId: string, row: feedsRepo.FeedRow | null): SiteFeedDto {
  return {
    siteId,
    enabled: row !== null && row.revokedAt === null,
    tokenHint: row?.tokenHint ?? null,
    tokenCreatedAt: row?.tokenCreatedAt.toISOString() ?? null,
    generatedAt: row?.generatedAt?.toISOString() ?? null,
    itemCount: row?.itemCount ?? null,
    kyeroCount: row?.kyeroCount ?? null,
    lastError: row?.lastError ?? null,
  };
}

async function assertSite(ctx: Ctx, siteId: string): Promise<void> {
  if (!(await repo.getSite(ctx.tx, ctx.tenant.agencyId, siteId))) throw new AppError('SITE_NOT_FOUND');
}

/** The site's feed as the dashboard shows it (members): whether it is on, the token's last characters, the last run. */
export async function getSiteFeed(ctx: Ctx, params: SiteParams): Promise<SiteFeedDto> {
  assertCan(ctx, 'websites.read');
  await assertSite(ctx, params.siteId);
  return toFeedDto(params.siteId, await feedsRepo.getFeed(ctx.tx, ctx.tenant.agencyId, params.siteId));
}

/** A retried rotation answers the same token this long (the `Idempotency-Key` replay window). */
export const FEED_TOKEN_IDEMPOTENCY_MS = 24 * 3_600_000;

/**
 * The token of a rotation sent with an `Idempotency-Key` (S7-07 review): derived from the key, the site and the
 * feed's version before the rotation, so a retry can answer it again without the token ever being stored. Another
 * rotation (or a revocation) moves the version on: an old key never brings an old token back.
 */
function derivedToken(siteId: string, versionBefore: number, idempotencyKey: string): string {
  if (!tokenKey) throw new Error('websites: configureSiteFeeds() was not called');
  return hmacSha256(tokenKey, 'websites.feed-token-derived', `${siteId}:${versionBefore}:${idempotencyKey}`);
}

function secretOf(siteId: string, row: feedsRepo.FeedRow, token: string): SiteFeedSecretDto {
  return {
    feed: toFeedDto(siteId, row),
    token,
    paths: { kyero: siteFeedPath(token, 'kyero.xml'), generic: siteFeedPath(token, 'inmolink.xml') },
  };
}

/**
 * Turns the site's feed on with a new token, or rotates it (agency admins). The token is in the answer only; the
 * previous one stops working at once. The feed is (re)generated by the worker within a minute. With an
 * `Idempotency-Key`, a retry within 24 h of the same rotation answers the same token (`replayed`) and rotates nothing.
 */
export async function rotateSiteFeed(
  ctx: Ctx,
  params: SiteParams,
  opts: { idempotencyKey?: string } = {},
): Promise<{ secret: SiteFeedSecretDto; replayed: boolean }> {
  assertCan(ctx, 'websites.manage');
  if (ctx.actor.kind !== 'user') throw new AppError('FORBIDDEN');
  await assertSite(ctx, params.siteId);
  const { agencyId } = ctx.tenant;
  const now = clock.now();
  const key = opts.idempotencyKey;
  const idempotencyHash = key ? tokenHashOf(`${params.siteId}:${key}`, 'websites.feed-token-idempotency') : null;
  const current = await feedsRepo.feedForRotation(ctx.tx, agencyId, params.siteId);
  if (
    key &&
    idempotencyHash &&
    current?.idempotencyHash &&
    current.revokedAt === null &&
    now.getTime() - current.tokenCreatedAt.getTime() < FEED_TOKEN_IDEMPOTENCY_MS &&
    safeEqual(current.idempotencyHash, idempotencyHash)
  ) {
    const token = derivedToken(params.siteId, current.version - 1, key);
    const row = await feedsRepo.getFeed(ctx.tx, agencyId, params.siteId);
    if (row && safeEqual(current.tokenHash, tokenHash(token)))
      return { secret: secretOf(params.siteId, row, token), replayed: true };
  }
  const token = key ? derivedToken(params.siteId, current?.version ?? 0, key) : newToken(32);
  const row = await feedsRepo.setFeedToken(ctx.tx, {
    siteId: params.siteId,
    agencyId,
    tokenHash: tokenHash(token),
    tokenHint: token.slice(-4),
    idempotencyHash,
    createdBy: ctx.actor.userId,
    now,
  });
  await emit(ctx.tx, websitesEvents.feedChanged({ siteId: params.siteId, agencyId, action: 'ROTATED' }));
  await compliance.audit(ctx, 'websites.feed.rotated', { type: 'site', id: params.siteId }, {});
  return { secret: secretOf(params.siteId, row, token), replayed: false };
}

/**
 * Turns the site's feed off (agency admins): its URL answers 404, its run is forgotten (the worker deletes the files)
 * and its CDN copies are purged.
 */
export async function revokeSiteFeed(ctx: Ctx, params: SiteParams): Promise<SiteFeedDto> {
  assertCan(ctx, 'websites.manage');
  if (ctx.actor.kind !== 'user') throw new AppError('FORBIDDEN');
  await assertSite(ctx, params.siteId);
  const { agencyId } = ctx.tenant;
  const row = await feedsRepo.revokeFeed(ctx.tx, agencyId, params.siteId, clock.now());
  if (!row) return toFeedDto(params.siteId, await feedsRepo.getFeed(ctx.tx, agencyId, params.siteId));
  await emit(ctx.tx, websitesEvents.feedChanged({ siteId: params.siteId, agencyId, action: 'REVOKED' }));
  await compliance.audit(ctx, 'websites.feed.revoked', { type: 'site', id: params.siteId }, {});
  return toFeedDto(params.siteId, row);
}

/** A live feed as feed-api serves it. */
export interface ServedFeed {
  siteId: string;
  agencyId: string;
  /** null until the first run finished. */
  runId: string | null;
  kyeroSha256: string | null;
  genericSha256: string | null;
}

/**
 * feed-api (`app_public`, no tenant yet): the live feed a token names, or null. Found by the token's keyed hash
 * (unique index), then the stored hash is compared in constant time — the row lookup never depends on the token's
 * characters beyond its hash. One statement; up to two inside an HMAC_KEY rotation window (S11-F13).
 */
export async function feedByToken(token: string): Promise<ServedFeed | null> {
  if (!tokenKey) throw new Error('websites: configureSiteFeeds() was not called');
  // S11-F13: inside an HMAC_KEY rotation window a URL issued under the previous key is found by its second hash (a
  // second statement only when the first misses); outside a window there is one candidate and one statement.
  const candidates = hmacSha256Candidates(tokenKey, TOKEN_PURPOSE, token);
  const row = await withPublicRead(async (tx) => {
    for (const hash of candidates) {
      const found = await feedsRepo.feedByTokenHash(tx, hash);
      if (found && safeEqual(found.tokenHash, hash)) return found;
    }
    return null;
  });
  if (!row) return null;
  return {
    siteId: row.siteId,
    agencyId: row.agencyId,
    runId: row.runId,
    kyeroSha256: row.kyeroSha256,
    genericSha256: row.genericSha256,
  };
}

